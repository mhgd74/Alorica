#!/usr/bin/env node
/**
 * Compiles the JSX sources under src/ to plain JavaScript the browser can load
 * as native ES modules.
 *
 * Why a build at all: Babel-standalone cannot transform imported files. Its
 * script-tag loader injects the compiled result inline and, for module scripts,
 * uses `modules: false`, so `import`/`export` are left to the browser — which
 * would then fetch any imported .jsx raw and choke on the JSX syntax. Compiling
 * ahead of time keeps the deploy a plain static site while letting the sources
 * stay split across real modules.
 *
 * The transform options mirror the ones Babel-standalone applies at runtime so
 * the output behaves exactly like the previous in-browser compilation.
 *
 * Usage: node scripts/build.js [--check]
 *   --check   verify the committed output is up to date, write nothing
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const Babel = require(path.join(ROOT, 'vendor', 'babel.min.js'));

const TRANSFORM_OPTIONS = {
  presets: ['react', ['env', { targets: { esmodules: true }, modules: false }]],
  plugins: ['transform-class-properties', 'transform-object-rest-spread'],
};

const GENERATED_BANNER = (from) =>
  `/* GENERATED FILE — compiled from ${from} by scripts/build.js.\n` +
  `   Do not edit this file; edit the .jsx source and run: npm run build */\n`;

const walk = (dir, out = []) => {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.isFile() && entry.name.endsWith('.jsx')) out.push(full);
  }
  return out;
};

const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');

const main = () => {
  const checkOnly = process.argv.includes('--check');
  const sources = walk(SRC).sort();

  if (!sources.length) {
    console.error('No .jsx sources found under ' + rel(SRC));
    process.exit(1);
  }

  let changed = 0;
  let failed = 0;

  for (const source of sources) {
    const sourceText = fs.readFileSync(source, 'utf8');
    const target = source.replace(/\.jsx$/, '.js');
    let compiled;

    try {
      compiled = Babel.transform(sourceText, {
        ...TRANSFORM_OPTIONS,
        filename: rel(source),
      }).code;
    } catch (err) {
      failed++;
      // Babel puts the file and position in the message already; keep the first
      // line only so a syntax error stays readable in the terminal.
      console.error(`FAIL  ${rel(source)}\n      ${String(err.message).split('\n')[0]}`);
      continue;
    }

    const output = GENERATED_BANNER(rel(source)) + compiled + '\n';
    const previous = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    const untouched = previous !== null && previous === output;

    if (untouched) {
      console.log(`ok    ${rel(target)}`);
      continue;
    }

    if (checkOnly) {
      console.error(`STALE ${rel(target)} — run: npm run build`);
      changed++;
      continue;
    }

    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, output);
    changed++;
    console.log(`${previous === null ? 'new  ' : 'built'} ${rel(target)}`);
  }

  console.log(`\n${sources.length} source(s), ${changed} updated, ${failed} failed`);
  if (failed || (checkOnly && changed)) process.exit(1);
};

main();
